// Flatten the published suite results into a Hugging Face dataset: one row per (platform, experiment, variant).
// Inputs are the suites already public in the agent-reliability-lab Space plus the local suite.
// Usage: node scripts/build-hf-dataset.mjs  →  artifacts/hf-dataset/{data/runs.jsonl,README.md,LICENSE}
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const SUITES = [
  ['local', 'artifacts/local-suite.json'],
  ['aws-lambda', 'artifacts/hf-space/aws-suite.json'],
  ['google-cloud-run-job', 'artifacts/hf-space/google-suite.json'],
];
const OUT = 'artifacts/hf-dataset';
mkdirSync(`${OUT}/data`, { recursive: true });

const rows = [];
for (const [platform, file] of SUITES) {
  const suite = JSON.parse(readFileSync(file, 'utf8'));
  for (const ex of suite.experiments) {
    for (const variant of ['before', 'after']) {
      const run = ex[variant];
      rows.push({
        platform,
        fixture_version: suite.fixture_version,
        source_sha256: suite.source_sha256,
        generated_at: suite.generated_at,
        node: suite.runtime.node,
        arch: suite.runtime.arch,
        experiment: ex.id,
        title: ex.title,
        change: ex.change,
        variant,
        scenario: run.scenario,
        client: run.client,
        timeout_ms: run.policy.timeout_ms,
        max_attempts: run.policy.max_attempts,
        retry: run.policy.retry,
        outcome: run.outcome,
        attempts: run.attempts.length,
        elapsed_ms: run.attempts.map((a) => a.elapsed_ms),
        transport_errors: run.transport_errors,
        findings: (run.clinic?.findings || []).map((f) => f.id),
        messages: JSON.stringify(run.trace.messages),
        trace_sha256: run.trace_sha256,
        suite_pass: suite.pass,
      });
    }
  }
}

const body = rows.map((r) => JSON.stringify(r)).join('\n') + '\n';
writeFileSync(`${OUT}/data/runs.jsonl`, body);
copyFileSync('LICENSE', `${OUT}/LICENSE`);
const sha = createHash('sha256').update(body).digest('hex');

